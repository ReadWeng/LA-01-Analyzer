def process_integration(fit_dir, lac_dir, output_html_path, base_html_path=None):
    """
    Main integration process.
    - Loads base/historical data.
    - Scans for FIT files and matches them with Excel/CSV sheets.
    - Generates new Chart.js HTML report.
    """
    # 1. Load existing historical data
    final_data = {}
    if base_html_path and os.path.exists(base_html_path):
        print(f"Loading historical data from {base_html_path}...")
        final_data = load_historical_data(base_html_path)
        print(f"Loaded {len(final_data)} historical sessions: {list(final_data.keys())}")
        
    # 2. Scan FIT files in fit_dir
    fit_files = glob.glob(os.path.join(fit_dir, "**/*.fit"), recursive=True) + glob.glob(os.path.join(fit_dir, "*.fit"))
    fit_files = list(set(fit_files)) # deduplicate
    
    print(f"Found {len(fit_files)} FIT files in {fit_dir}")
    
    # 3. Scan Lactate files in lac_dir
    lac_files = glob.glob(os.path.join(lac_dir, "*.xlsx")) + glob.glob(os.path.join(lac_dir, "*.csv"))
    print(f"Found {len(lac_files)} Lactate sheets in {lac_dir}")
    
    # Parse each lactate sheet and try to find a matching FIT file
    for lac_file in lac_files:
        basename = os.path.basename(lac_file)
        # Try to extract date pattern (YYYY-MM-DD) from filename
        date_match = re.search(r'(\d{4}-\d{2}-\d{2})', basename)
        if not date_match:
            continue
            
        session_date = date_match.group(1)
        print(f"\nProcessing session date: {session_date}...")
        
        # Parse lactate sheet
        df_lac = parse_lactate_file(lac_file)
        if df_lac.empty:
            print(f"  [Warning] Lactate file empty or invalid: {basename}")
            continue
            
        # Find matching FIT file (by date in filepath or start time)
        matching_fit_path = None
        for fit_path in fit_files:
            # Check if filename contains the date
            if session_date.replace("-", "") in os.path.basename(fit_path) or session_date in fit_path:
                matching_fit_path = fit_path
                break
                
        # If not matched by filename, let's parse the fit file start time to match
        if not matching_fit_path:
            for fit_path in fit_files:
                try:
                    # Quick parse start time
                    fit_file = fitparse.FitFile(fit_path)
                    for message in fit_file.get_messages('record'):
                        first_ts = message.get_value('timestamp')
                        if first_ts:
                            fit_date = first_ts.strftime('%Y-%m-%d')
                            if fit_date == session_date:
                                matching_fit_path = fit_path
                                break
                    if matching_fit_path:
                        break
                except Exception:
                    pass
                    
        df_fit_down = pd.DataFrame()
        start_time_str = session_date
        
        if matching_fit_path:
            print(f"  Found matching FIT file: {os.path.basename(matching_fit_path)}")
            try:
                df_fit, start_time = parse_fit_file(matching_fit_path)
                if not df_fit.empty:
                    df_fit_down = smooth_and_downsample(df_fit, downsample_seconds=10)
                    start_time_str = start_time.strftime('%Y-%m-%d %H:%M:%S')
            except Exception as e:
                print(f"  [Error] Failed to parse matched FIT file: {e}")
        else:
            print(f"  [Info] No matching FIT file found for {session_date}.")
            # If historical data exists for this date, let's keep it!
            if session_date in final_data:
                print(f"  Keeping existing historical FIT data for {session_date}.")
                df_fit_down = pd.DataFrame() # empty so we don't overwrite
                
        # Prepare datasets to inject
        power_30s = []
        hr_30s = []
        temp_10s = []
        
        if not df_fit_down.empty:
            for _, r in df_fit_down.iterrows():
                power_30s.append({'x': r['elapsed_minutes'], 'y': r['power_smoothed']})
                hr_30s.append({'x': r['elapsed_minutes'], 'y': r['hr_smoothed']})
                temp_10s.append({'x': r['elapsed_minutes'], 'y': r['core_temp']})
        elif session_date in final_data:
            # Carry over historical continuous curves
            power_30s = final_data[session_date].get('power_30s', [])
            hr_30s = final_data[session_date].get('hr_30s', [])
            temp_10s = final_data[session_date].get('temp_10s', [])
            start_time_str = final_data[session_date].get('startTime', start_time_str)
            
        # Parse lactate/glucose points
        lactate_points = []
        glucose_points = []
        
        for _, r in df_lac.iterrows():
            t = r['elapsed_minutes']
            # Align with FIT metrics if fit data is available
            aligned_p = None
            aligned_h = None
            aligned_t = None
            
            if not df_fit_down.empty:
                diffs = (df_fit_down['elapsed_minutes'] - t).abs()
                closest_idx = diffs.idxmin()
                closest = df_fit_down.iloc[closest_idx]
                aligned_p = closest['power_smoothed']
                aligned_h = closest['hr_smoothed']
                aligned_t = closest['core_temp']
                
            lac_val = r['lactate']
            glu_val = r['glucose']
            
            if lac_val is not None:
                item = {'x': t, 'y': lac_val, 'source': r['source']}
                if aligned_p is not None: item['power'] = int(aligned_p) if pd.notna(aligned_p) else None
                if aligned_h is not None: item['hr'] = int(aligned_h) if pd.notna(aligned_h) else None
                if aligned_t is not None: item['temp'] = round(aligned_t, 2) if pd.notna(aligned_t) else None
                lactate_points.append(item)
                
            if glu_val is not None:
                item = {'x': t, 'y': glu_val, 'source': r['source']}
                if aligned_p is not None: item['power'] = int(aligned_p) if pd.notna(aligned_p) else None
                if aligned_h is not None: item['hr'] = int(aligned_h) if pd.notna(aligned_h) else None
                if aligned_t is not None: item['temp'] = round(aligned_t, 2) if pd.notna(aligned_t) else None
                glucose_points.append(item)
                
        # If no new FIT data is parsed but we had historical stats, compute stats from new Excel data
        # mixed with whatever FIT data we had.
        # Let's rebuild the temporary dataframes for stats calculation
        df_fit_temp = pd.DataFrame()
        if power_30s:
            df_fit_temp = pd.DataFrame({
                'power_smoothed': [pt['y'] for pt in power_30s],
                'hr_smoothed': [pt['y'] for pt in hr_30s],
                'core_temp': [pt['y'] for pt in temp_10s]
            })
            
        stats = compute_session_stats(df_fit_temp, df_lac)
        
        # Save or update session
        final_data[session_date] = {
            'startTime': start_time_str,
            'power_30s': power_30s,
            'hr_30s': hr_30s,
            'temp_10s': temp_10s,
            'lactate': lactate_points,
            'glucose': glucose_points,
            'stats': stats
        }
        
    if not final_data:
        print("[Error] No session data available to integrate. Exiting.")
        return False
        
    # 4. Generate final HTML contents
    print("\nGenerating final integrated HTML...")
    html_content = build_integrated_html(final_data)
    
    os.makedirs(os.path.dirname(output_html_path), exist_ok=True)
    with open(output_html_path, 'w', encoding='utf-8') as f:
        f.write(html_content)
        
    print(f"[Success] Multi-session integrated report generated at: {output_html_path}")
    return True

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Lactate Multi-Session Integration Report Generator")
    parser.add_argument("--fit-dir", default="0521", help="Directory containing .fit files")
