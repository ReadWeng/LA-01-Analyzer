def decode_plotly_array(val):
    if isinstance(val, list):
        return val
    elif isinstance(val, dict) and 'bdata' in val:
        dtype_map = {
            'f8': np.float64,
            'f4': np.float32,
            'i8': np.int64,
            'i4': np.int32,
            'i2': np.int16,
            'i1': np.int8,
            'u8': np.uint64,
            'u4': np.uint32,
            'u2': np.uint16,
            'u1': np.uint8,
        }
        dt_cls = dtype_map.get(val.get('dtype'), np.float64)
        try:
            bdata_str = str(val['bdata'])
            bdata_str += '=' * (-len(bdata_str) % 4)
            raw_bytes = base64.b64decode(bdata_str)
            itemsize = np.dtype(dt_cls).itemsize
            rem = len(raw_bytes) % itemsize
            if rem != 0:
                raw_bytes = raw_bytes[:-rem]
            if not raw_bytes:
                return []
            arr = np.frombuffer(raw_bytes, dtype=dt_cls)
            return [None if np.isnan(v) else float(v) for v in arr]
        except Exception:
            return []
    return []

def parse_single_session_html(html_source):
    """
    Parses a single-session HTML report (generated by generate_html_report).
    html_source can be a file path (str), HTML string content (str), or bytes object.
    Returns (date_str, session_dict).
    """
    if isinstance(html_source, bytes):
        html_content = html_source.decode('utf-8', errors='ignore')
    elif isinstance(html_source, str) and os.path.exists(html_source):
        with open(html_source, 'r', encoding='utf-8', errors='ignore') as f:
            html_content = f.read()
    elif isinstance(html_source, str):
        html_content = html_source
    else:
        return None, {}

    session = {
        'startTime': None,
        'power_30s': [],
        'hr_30s': [],
        'temp_10s': [],
        'lactate': [],
        'glucose': [],
        'stats': {}
    }
    
    # 1. Parse Metadata (Start Time, Date)
    st_match = re.search(r'活動開始時間.*?:?\s*([\d\-:\s]+)', html_content)
    if st_match:
        st_str = st_match.group(1).strip()
        session['startTime'] = st_str
        date_match = re.search(r'(\d{4}-\d{2}-\d{2})', st_str)
        date_str = date_match.group(1) if date_match else st_str[:10]
    else:
        date_str = "Unknown Date"
        
    # 2. Parse KPI Cards for stats
    kpi_matches = re.findall(r'<div class="kpi-card">\s*<div class="kpi-label">(.*?)</div>\s*<div class="kpi-value"[^>]*>(.*?)</div>', html_content, re.DOTALL)
    for label, val in kpi_matches:
        label_clean = re.sub(r'<[^>]+>', '', label).strip()
        val_clean = re.sub(r'<[^>]+>', '', val).strip()
        if "時長" in label_clean:
            session['stats']['duration'] = val_clean
        elif "功率" in label_clean:
            parts = val_clean.replace("W", "").split("/")
            if len(parts) == 2:
                try:
                    session['stats']['avg_power'] = int(parts[0].strip())
                    session['stats']['max_power'] = int(parts[1].strip())
                except ValueError:
                    pass
        elif "心率" in label_clean:
            parts = val_clean.replace("bpm", "").split("/")
            if len(parts) == 2:
                try:
                    session['stats']['avg_hr'] = int(parts[0].strip())
                    session['stats']['max_hr'] = int(parts[1].strip())
                except ValueError:
                    pass
        elif "溫度" in label_clean:
            session['stats']['max_temp'] = val_clean.replace("°C", "").strip()

    # 3. Parse Summary Table with Regex
    table_match = re.search(r'<table[^>]*summary-table[^"]*"[^>]*>(.*?)</table>', html_content, re.DOTALL)
    if table_match:
        table_html = table_match.group(1)
        headers = [re.sub(r'<[^>]+>', '', th).strip() for th in re.findall(r'<th[^>]*>(.*?)</th>', table_html, re.DOTALL)]
        tr_matches = re.findall(r'<tr[^>]*>(.*?)</tr>', table_html, re.DOTALL)
        for tr in tr_matches:
            tds = [re.sub(r'<[^>]+>', '', td).strip() for td in re.findall(r'<td[^>]*>(.*?)</td>', tr, re.DOTALL)]
            if tds and len(tds) == len(headers):
                row_dict = dict(zip(headers, tds))
                t_val = row_dict.get('量測時間 (分)')
                lac_val = row_dict.get('乳酸值 (mmol/L)')
                glu_val = row_dict.get('血糖值 (mg/dL)')
                src_val = row_dict.get('量測點來源', '自訂時間')
                pw_val = row_dict.get('對應功率 (W)')
                hr_val = row_dict.get('對應心率 (BPM)')
                tp_val = row_dict.get('對應核心溫度 (°C)')
                
                if t_val:
                    try:
                        t_float = float(t_val)
                        if lac_val and lac_val != "-":
                            item = {'x': t_float, 'y': float(lac_val), 'source': src_val}
                            if pw_val and pw_val != "-": item['power'] = int(float(pw_val))
                            if hr_val and hr_val != "-": item['hr'] = int(float(hr_val))
                            if tp_val and tp_val != "-": item['temp'] = float(tp_val)
                            session['lactate'].append(item)
                        if glu_val and glu_val != "-":
                            item = {'x': t_float, 'y': int(float(glu_val)), 'source': src_val}
                            if pw_val and pw_val != "-": item['power'] = int(float(pw_val))
                            if hr_val and hr_val != "-": item['hr'] = int(float(hr_val))
                            if tp_val and tp_val != "-": item['temp'] = float(tp_val)
                            session['glucose'].append(item)
                    except ValueError:
                        pass

    # 4. Parse Plotly Traces for timeseries (Power 30s, HR 30s, Core Temp 10s)
    match = re.search(r'Plotly\.newPlot\(\s*"[^"]+"\s*,\s*(\[.*?\])\s*,\s*(\{.*?\})\s*[\),]', html_content, re.DOTALL)
    if match:
        traces = json.loads(match.group(1))
        for t in traces:
            name = str(t.get('name', ''))
            x_arr = decode_plotly_array(t.get('x'))
            y_arr = decode_plotly_array(t.get('y'))
            
            if "30s" in name or "功率" in name:
                if not session['power_30s'] and len(x_arr) == len(y_arr):
                    step = max(1, len(x_arr) // 500)
                    for i in range(0, len(x_arr), step):
                        if y_arr[i] is not None:
                            session['power_30s'].append({'x': round(x_arr[i], 2), 'y': round(y_arr[i], 1)})
            elif "心率" in name:
                if not session['hr_30s'] and len(x_arr) == len(y_arr):
                    step = max(1, len(x_arr) // 500)
                    for i in range(0, len(x_arr), step):
                        if y_arr[i] is not None:
                            session['hr_30s'].append({'x': round(x_arr[i], 2), 'y': round(y_arr[i], 1)})
            elif "核心溫度" in name or "溫度" in name:
                if not session['temp_10s'] and len(x_arr) == len(y_arr):
                    step = max(1, len(x_arr) // 500)
                    for i in range(0, len(x_arr), step):
                        if y_arr[i] is not None:
                            session['temp_10s'].append({'x': round(x_arr[i], 2), 'y': round(y_arr[i], 2)})
            elif "乳酸" in name and not session['lactate']:
                for xi, yi in zip(x_arr, y_arr):
                    if xi is not None and yi is not None:
                        session['lactate'].append({'x': round(xi, 2), 'y': round(yi, 2), 'source': '報告圖表'})
            elif "血糖" in name and not session['glucose']:
                for xi, yi in zip(x_arr, y_arr):
                    if xi is not None and yi is not None:
                        session['glucose'].append({'x': round(xi, 2), 'y': round(yi, 1), 'source': '報告圖表'})

    # Calculate max lactate / max glucose in stats if not present
    if session['lactate']:
        max_lac = max(pt['y'] for pt in session['lactate'] if pt.get('y') is not None)
        session['stats']['max_lactate'] = f"{max_lac:.1f} mmol/L"
    if session['glucose']:
        max_glu = max(pt['y'] for pt in session['glucose'] if pt.get('y') is not None)
        session['stats']['max_glucose'] = f"{int(max_glu)} mg/dL"

    return date_str, session

def load_historical_data(html_path):
    """
    Extracts rawLactateData from an existing integrated HTML report.
    This acts as a backup seed if the original FIT files are missing.
    """
    if not os.path.exists(html_path):
        return {}
    try:
        with open(html_path, 'r', encoding='utf-8') as f:
            content = f.read()
        match = re.search(r'const rawLactateData\s*=\s*(\{.*?\});', content, re.DOTALL)
        if match:
            return json.loads(match.group(1))
    except Exception as e:
        print(f"[Warning] Failed to parse historical HTML data from {html_path}: {e}")
    return {}

def parse_fit_file(fit_source):
    """
    Parses a FIT file and returns a cleaned timeseries DataFrame and start time.
    fit_source can be a filepath (str) or a bytes object.
    """
    if isinstance(fit_source, bytes):
        fit_file = fitparse.FitFile(io.BytesIO(fit_source))
    else:
        fit_file = fitparse.FitFile(fit_source)
        
    records = []
    for record in fit_file.get_messages('record'):
        vals = {field.name: field.value for field in record.fields}
        records.append(vals)
        
    df = pd.DataFrame(records)
    if df.empty or 'timestamp' not in df.columns:
        return pd.DataFrame(), None
        
    df = df.sort_values(by='timestamp').reset_index(drop=True)
    df['timestamp'] = pd.to_datetime(df['timestamp'])
    if df['timestamp'].dt.tz is not None:
        df['timestamp'] = df['timestamp'].dt.tz_localize(None)
    df['timestamp'] = df['timestamp'] + pd.Timedelta(hours=8)
    start_time = df['timestamp'].iloc[0]
    
    # Calculate elapsed minutes from start
    df['elapsed_minutes'] = (df['timestamp'] - start_time).dt.total_seconds() / 60.0
    
    # Parse core temperature
    if 'core_temperature' in df.columns:
        df['core_temp'] = df['core_temperature'].apply(lambda x: x / 100.0 if (pd.notna(x) and x > 1000) else x)
    elif 'unknown_139' in df.columns:
        df['core_temp'] = df['unknown_139'].apply(lambda x: x / 100.0 if (pd.notna(x) and x > 1000) else x)
    else:
        df['core_temp'] = np.nan
        
    # Ensure standard columns are present
    for col in ['heart_rate', 'power']:
        if col not in df.columns:
            df[col] = np.nan
            
    df_clean = df[['timestamp', 'elapsed_minutes', 'heart_rate', 'power', 'core_temp']].copy()
    return df_clean, start_time

def smooth_and_downsample(df, downsample_seconds=10):
    """
    Applies 30s rolling average smoothing on Power and HR, then downsamples the FIT series.
    """
    if df.empty:
        return pd.DataFrame()
        
    df = df.copy()
    if 'power' in df.columns and df['power'].notna().any():
        df['power_smoothed'] = df['power'].rolling(window=30, min_periods=1).mean()
    else:
        df['power_smoothed'] = np.nan
        
    if 'heart_rate' in df.columns and df['heart_rate'].notna().any():
        df['hr_smoothed'] = df['heart_rate'].rolling(window=30, min_periods=1).mean()
    else:
        df['hr_smoothed'] = np.nan
        
    # Downsampling to standard interval
    step_minutes = downsample_seconds / 60.0
    df['grid_time'] = (df['elapsed_minutes'] / step_minutes).round() * step_minutes
    
    df_downsampled = df.groupby('grid_time').agg({
        'power_smoothed': lambda x: x.mean() if x.notna().any() else np.nan,
        'hr_smoothed': lambda x: x.mean() if x.notna().any() else np.nan,
        'core_temp': lambda x: x.mean() if x.notna().any() else np.nan
    }).reset_index()
    
    df_downsampled = df_downsampled.rename(columns={'grid_time': 'elapsed_minutes'})
    # Convert NaNs to None for JSON compliance
    df_downsampled = df_downsampled.replace({np.nan: None})
    return df_downsampled

def find_column_name(df, patterns):
    cols = df.columns
    for col in cols:
        col_lower = str(col).strip().lower()
        for pat in patterns:
            if col_lower == pat.lower():
                return col
    for col in cols:
        col_lower = str(col).strip().lower()
        for pat in patterns:
            if pat.lower() in col_lower:
                return col
    return None

def parse_lactate_file(file_source):
    """
    Parses a lactate sheet (Excel or CSV).
    Returns DataFrame with ['elapsed_minutes', 'lactate', 'glucose', 'source'] columns.
    """
    if isinstance(file_source, bytes):
        try:
            df = pd.read_excel(io.BytesIO(file_source))
        except Exception:
            try:
                df = pd.read_csv(io.BytesIO(file_source))
            except Exception:
                return pd.DataFrame()
    else:
        ext = os.path.splitext(file_source)[1].lower()
        try:
            if ext in ['.xlsx', '.xls']:
                df = pd.read_excel(file_source)
            else:
                df = pd.read_csv(file_source)
        except Exception:
            return pd.DataFrame()
            
    time_col = find_column_name(df, ["相對時間", "時間", "time", "elapsed", "duration", "min", "分鐘", "分"])
    lac_col = find_column_name(df, ["乳酸", "lac", "mmol"])
    glu_col = find_column_name(df, ["血糖", "glucose", "glu", "mg/dl", "mg"])
    src_col = find_column_name(df, ["來源", "source", "量測點來源"])
    
    if time_col is None:
        return pd.DataFrame()
        
    res_df = pd.DataFrame()
    res_df['elapsed_minutes'] = pd.to_numeric(df[time_col], errors='coerce')
    
    if lac_col is not None:
        res_df['lactate'] = pd.to_numeric(df[lac_col], errors='coerce')
    else:
        res_df['lactate'] = np.nan
        
    if glu_col is not None:
        res_df['glucose'] = pd.to_numeric(df[glu_col], errors='coerce')
    else:
        res_df['glucose'] = np.nan
        
    if src_col is not None:
        res_df['source'] = df[src_col].fillna("自訂時間").astype(str)
    else:
        res_df['source'] = "自訂時間"
        
    res_df = res_df.dropna(subset=['elapsed_minutes']).sort_values(by='elapsed_minutes').reset_index(drop=True)
    res_df = res_df.replace({np.nan: None})
    return res_df

def compute_session_stats(df_fit_down, df_lac):
    stats = {
        'max_power': '-',
        'avg_power': '-',
        'max_hr': '-',
        'avg_hr': '-',
        'max_temp': '-',
        'max_lactate': '-',
        'max_glucose': '-'
    }
    
    if not df_fit_down.empty:
        # Convert values back to float (ignoring None/NaN) for computation
        pw = [p for p in df_fit_down['power_smoothed'] if p is not None and pd.notna(p)]
        if pw:
            stats['max_power'] = int(max(pw))
            stats['avg_power'] = int(sum(pw)/len(pw))
            
        hr = [h for h in df_fit_down['hr_smoothed'] if h is not None and pd.notna(h)]
        if hr:
            stats['max_hr'] = int(max(hr))
            stats['avg_hr'] = int(sum(hr)/len(hr))
            
        temp = [t for t in df_fit_down['core_temp'] if t is not None and pd.notna(t)]
        if temp:
            stats['max_temp'] = f"{max(temp):.2f}"
            
    if not df_lac.empty:
        lac = [l for l in df_lac['lactate'] if l is not None and pd.notna(l)]
        if lac:
            stats['max_lactate'] = f"{max(lac):.1f} mmol/L"
            
        glu = [g for g in df_lac['glucose'] if g is not None and pd.notna(g)]
        if glu:
            stats['max_glucose'] = f"{int(max(glu))} mg/dL"
            
    return stats

